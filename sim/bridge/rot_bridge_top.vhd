-- Simulation top for the GHDL <-> Renode bridge. Reads one request per line
-- from stdin, drives the RoT bus, and answers on stdout:
--   P                 -> OK
--   R <addr8>         -> OK <data8>
--   W <addr8> <data8> -> OK
-- (numbers are 8 hex digits). End of input or "Q" finishes the simulation.

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use std.textio.all;
use std.env.finish;
use work.rot_pkg.all;
use work.rot_otp_pkg.all;   -- generated by the bridge: constant OTP_HASH

entity rot_bridge_top is
end entity rot_bridge_top;

architecture sim of rot_bridge_top is
    signal clk       : std_logic := '0';
    signal rst_n     : std_logic := '0';
    signal bus_sel   : std_logic := '0';
    signal bus_wr    : std_logic := '0';
    signal bus_addr  : std_logic_vector(11 downto 0) := (others => '0');
    signal bus_wdata : std_logic_vector(31 downto 0) := (others => '0');
    signal bus_rdata : std_logic_vector(31 downto 0);
begin
    clk <= not clk after 5 ns;

    dut : entity work.rot_peripheral
        generic map (PUBKEY_HASH => OTP_HASH)
        port map (
            clk       => clk,
            rst_n     => rst_n,
            bus_sel   => bus_sel,
            bus_wr    => bus_wr,
            bus_addr  => bus_addr,
            bus_wdata => bus_wdata,
            bus_rdata => bus_rdata);

    bridge : process
        variable l_in, l_out    : line;
        variable cmd            : character;
        variable addr32, data32 : std_logic_vector(31 downto 0);
        variable rd             : std_logic_vector(31 downto 0);

        procedure respond(text : string; with_data : boolean;
                          d : std_logic_vector(31 downto 0)) is
            variable lo : line;
        begin
            write(lo, text);
            if with_data then
                write(lo, string'(" "));
                hwrite(lo, d);
            end if;
            writeline(output, lo);
            flush(output);
        end procedure;
    begin
        -- Power-on reset.
        rst_n <= '0';
        wait for 30 ns;
        rst_n <= '1';
        wait until rising_edge(clk);
        wait for 1 ns;

        while not endfile(input) loop
            readline(input, l_in);
            if l_in'length = 0 then
                next;
            end if;
            read(l_in, cmd);
            case cmd is
                when 'P' =>
                    respond("OK", false, x"00000000");

                when 'R' =>
                    hread(l_in, addr32);
                    bus_sel  <= '1';
                    bus_wr   <= '0';
                    bus_addr <= addr32(11 downto 0);
                    wait for 1 ns;           -- reads are combinational
                    rd := bus_rdata;
                    bus_sel <= '0';
                    respond("OK", true, rd);

                when 'W' =>
                    hread(l_in, addr32);
                    hread(l_in, data32);
                    bus_sel   <= '1';
                    bus_wr    <= '1';
                    bus_addr  <= addr32(11 downto 0);
                    bus_wdata <= data32;
                    wait until rising_edge(clk);
                    wait for 1 ns;
                    bus_sel <= '0';
                    bus_wr  <= '0';
                    respond("OK", false, x"00000000");

                when 'Q' =>
                    exit;

                when others =>
                    respond("ERR bad command", false, x"00000000");
            end case;
        end loop;

        finish;
        wait;
    end process bridge;
end architecture sim;